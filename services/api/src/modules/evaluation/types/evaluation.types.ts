import { Document, Types } from "mongoose";

export enum EvaluationStatus {
  NOT_STARTED = "NOT_STARTED",
  IN_PROGRESS = "IN_PROGRESS",
  COMPLETED = "COMPLETED",
  PUBLISHED = "PUBLISHED",
}

export enum HiringRecommendation {
  STRONG_HIRE = "STRONG_HIRE",
  HIRE = "HIRE",
  BORDERLINE = "BORDERLINE",
  NO_HIRE = "NO_HIRE",
}

export interface SkillScores {
  technical: number;
  communication: number;
  problemSolving: number;
  confidence: number;
  /** NEW in v2 — may be 0 on older evaluations that pre-date this field. */
  leadership: number;
  criticalThinking: number;
}

/**
 * Structured gap between a candidate's current score and the benchmark
 * expected for the role/level they interviewed for. Distinct from Coach's
 * roadmap — this is a diagnosis, not a learning plan.
 */
export interface SkillGap {
  skill: string;
  currentLevel: number;  // 0-100, mirroring the skill score
  targetLevel: number;   // 0-100, role-appropriate benchmark
  priority: "high" | "medium" | "low";
  actionableSteps: string[];
}

export interface QuestionEvaluation {
  turnNumber: number;
  question: string;
  answer: string;
  score: number;
  feedback: string;
}

export interface EvaluationMetadata {
  provider?: string;
  model?: string;
  promptVersion?: string;
  latencyMs?: number;
  tokensUsed?: number;
}

export interface EvaluationDocument extends Document {
  interviewSessionId: Types.ObjectId;

  organizationId?: Types.ObjectId;

  candidateId: Types.ObjectId;

  status: EvaluationStatus;

  overallScore: number;

  skillScores: SkillScores;

  strengths: string[];

  weaknesses: string[];

  recommendations: string[];

  overallSummary: string;

  hiringRecommendation: HiringRecommendation;

  questionEvaluations: QuestionEvaluation[];

  /** Present only for evaluations generated by prompt v2+. */
  skillGaps: SkillGap[];

  metadata: EvaluationMetadata;

  publishedAt?: Date;

  createdAt: Date;

  updatedAt: Date;
}